/**
 * The speech models dictation can download, from transcribe.cpp's converted weights on Hugging
 * Face. Each is pinned by revision, size and SHA-256, so the bytes are verified, not trusted. Taken
 * from Pi Voice's catalog (earendil-works/pi-voice@df38132), which pins the same files.
 */
export interface DictationModel {
  readonly id: string;
  readonly name: string;
  readonly description: string;
  readonly repository: string;
  readonly revision: string;
  readonly filename: string;
  readonly size: number;
  readonly sha256: string;
  /** BCP 47 codes the model transcribes. */
  readonly languages: ReadonlyArray<string>;
  /** Transcribes while you speak; others transcribe the recording when you stop. */
  readonly streaming: boolean;
  /** Tells the language itself, so it can be left on Auto. */
  readonly languageDetection: boolean;
  /** Offered first: a small set that covers most people. */
  readonly recommended: boolean;
}

